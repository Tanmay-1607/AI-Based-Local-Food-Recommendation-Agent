export function getOfflineRecommendations({ query = '', cuisine = null, max_budget = null, food_type = null, top_n = 15 } = {}) {
  let list = [...NAGPUR_FOOD_DATASET];
  const rawQ = (query || '').trim().toLowerCase();

  // Detect sweet intent
  const isSweet = rawQ.includes('sweet') || rawQ.includes('dessert') || rawQ.includes('barfi') || 
                  rawQ.includes('mithai') || rawQ.includes('jalebi') || rawQ.includes('ice cream') || 
                  rawQ.includes('kulfi') || rawQ.includes('rabdi') || (cuisine && cuisine.includes('Sweet'));

  // Detect spicy intent
  const isSpicy = rawQ.includes('spicy') || rawQ.includes('saoji') || rawQ.includes('fiery') || 
                  rawQ.includes('teekha') || rawQ.includes('tarri') || (cuisine && cuisine.toLowerCase().includes('saoji'));

  // Detect breakfast intent
  const isBreakfast = rawQ.includes('breakfast') || rawQ.includes('poha') || rawQ.includes('misal') || 
                      rawQ.includes('idli') || rawQ.includes('dosa');

  // Filter by cuisine if specified or inferred
  let targetCuisine = cuisine;
  if (isSweet && !cuisine) targetCuisine = "Sweets & Desserts";
  else if (isSpicy && !cuisine) targetCuisine = "Saoji";

  if (targetCuisine && targetCuisine !== 'all') {
    list = list.filter(item => item.cuisine.toLowerCase() === targetCuisine.toLowerCase());
  }

  // Strict sweet gating: NEVER include spicy items
  if (isSweet) {
    list = list.filter(item => item.cuisine === "Sweets & Desserts" && item.spice_level === 1);
  } else if (isSpicy) {
    list = list.filter(item => item.cuisine !== "Sweets & Desserts" && item.spice_level >= 3);
  }

  // Dietary filter
  if (food_type && food_type !== 'all') {
    if (food_type === 'veg') {
      list = list.filter(item => item.food_type === 'veg');
    } else if (food_type === 'non-veg') {
      list = list.filter(item => item.food_type === 'non-veg' || item.food_type === 'egg');
    }
  }

  // Budget filter
  if (max_budget && max_budget > 0) {
    list = list.filter(item => item.price <= max_budget);
  }

  // Keyword search scoring
  if (rawQ && !isSweet && !isSpicy) {
    const tokens = rawQ.split(/\s+/).filter(t => t.length > 2);
    if (tokens.length > 0) {
      list = list.filter(item => {
        const haystack = `${item.dish_name} ${item.cuisine} ${item.locality} ${item.description}`.toLowerCase();
        return tokens.some(t => haystack.includes(t));
      });
    }
  }

  // If filtered list is empty, relax constraints gracefully
  if (list.length === 0) {
    if (isSweet) list = NAGPUR_FOOD_DATASET.filter(i => i.cuisine === "Sweets & Desserts");
    else if (isSpicy) list = NAGPUR_FOOD_DATASET.filter(i => i.spice_level >= 3);
    else list = [...NAGPUR_FOOD_DATASET];
  }

  // Sort by rating descending, then budget
  list.sort((a, b) => b.rating - a.rating || a.price - b.price);

  return list.slice(0, top_n);
}

